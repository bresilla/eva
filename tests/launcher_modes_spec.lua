-- Every mode the launcher has, on the real shell. What a mode asks of the machine
-- is stood in for with `test.stub_run`; its parsing, its rows and what Return does
-- are the real thing.
--
--     morf test --no-dbus tests/launcher_modes_spec.lua

local test = morf.test
local host = assert(load(morf.fs.read(morf.env("PWD") .. "/tests/fixtures/launcher_host.lua")))()

local function landed(name)
  return test.wait(function()
    test.advance(16)
    return host.row(name)
  end, 3000, "never listed: " .. name)
end

test.describe("the holes that were open", function()
  test.it("reads the clipboard from eva-clipboard's store, with pins and pictures", function()
    local state = morf.env("XDG_STATE_HOME") .. "/eva/clipboard"
    local picture = state .. "/shot.png"
    host.write(picture, morf.fs.read(morf.env("PWD") .. "/tests/fixtures/wallpaper.png"))
    host.write(state .. "/history.json", morf.json.encode {
      { id = "1", kind = "text", text = "pinned words", pinned = true, time = morf.time.now_ms() },
      { id = "2", kind = "text", text = "https://example.org/x", time = morf.time.now_ms() },
      { id = "3", kind = "image", path = picture, mime = "image/png", time = morf.time.now_ms() },
    })
    host.load()
    host.search(";")
    local rows = test.ipc("rows")
    test.eq(rows[1].name, "pinned words")
    test.matches(rows[1].description, "Pinned")
    test.eq(rows[2].name, "https://example.org/x")
    test.eq(rows[3].name, "Picture")
    host.search("; img")
    test.eq(host.names(), { "Picture" })
    host.search("; link")
    test.eq(host.names(), { "https://example.org/x" })
    host.search("; pinned")
    test.eq(host.names(), { "pinned words" })
    host.search(";")
    test.ipc("activate")
    test.settle(400)
    test.falsy(test.ipc("state").open)
  end)

  test.it("pins through the one store, and hears what eva-clipboard writes", function()
    local state = morf.env("XDG_STATE_HOME") .. "/eva/clipboard/history.json"
    host.write(state, morf.json.encode { { id = "a", kind = "text", text = "first", time = morf.time.now_ms() } })
    host.load()
    host.search(";")
    test.ipc("do_action", "Pin it")
    test.advance(100)
    test.matches(morf.fs.read(state), '"pinned":true')
    host.write(state, morf.json.encode {
      { id = "b", kind = "text", text = "from the other process", time = morf.time.now_ms() } })
    landed("from the other process")
  end)

  test.it("reads no clipse file", function()
    test.falsy(morf.fs.exists(morf.env("PWD") .. "/lib/integrations/clipse.lua"))
    test.falsy(morf.fs.read(morf.env("PWD") .. "/shell/providers.lua"):find("clipse", 1, true))
  end)

  test.it("takes wallpapers from lule.folder", function()
