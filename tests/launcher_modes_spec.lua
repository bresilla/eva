    host.write(folder .. "/sea.png", morf.fs.read(morf.env("PWD") .. "/tests/fixtures/wallpaper.png"))
    host.write(folder .. "/not-a-picture.txt", "no")
    host.load { settings = { lule = { folder = folder } } }
