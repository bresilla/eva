test.describe("the rest of the house", function()
  test.it("lists every mode after >", function()
    host.load()
    host.search("> ")
    local names = {}
    for _, name in ipairs(host.names()) do names[name] = true end
    for _, name in ipairs { "Timer", "Translate", "Dictionary", "Password", "QR code", "Processes", "Ports", "Manual",
      "Services", "SSH", "Nix packages", "Wi-Fi", "Bluetooth", "Sound output", "Recent files", "Snippets", "Bookmarks" } do
      test.truthy(names[name], "no mode " .. name)
    end
  end)

  test.it("keeps an alias", function()
    host.load()
    host.search("> alias add fb fixture browser")
    test.ipc("activate")
    test.settle(300)
    test.ipc("launcher", "open")
    test.settle(300)
