-- Universal search, the action panel, the keyboard, and answers landing late, on
-- the real shell.
--
--     morf test --no-dbus tests/launcher_search_spec.lua

local test = morf.test
local host = assert(load(morf.fs.read(morf.env("PWD") .. "/tests/fixtures/launcher_host.lua")))()

test.describe("universal search", function()
  test.it("finds a Settings page with no prefix, and opens it", function()
    host.load()
    host.search("charge limit")
    local row = host.row("Charge limit")
    test.truthy(row, "no Settings control found")
    test.eq(row.tag, "Setting")
    test.eq(test.ipc("chosen"), "Charge limit")
    test.key("Return")
    test.settle(800)
    test.truthy(test.ipc("sidebar_open"))
    test.eq(test.ipc("settings_detail"), "power")
    test.falsy(test.ipc("state").open)
  end)

  test.it("reaches apps, pages, tiles, actions, modes and files from one box", function()
    host.load { path = { "fd" }, settings = { launcher = { sources = { "apps", "settings", "system", "actions", "modes", "files" } } } }
    test.stub_run("fd", { code = 0, stdout = morf.env("XDG_CACHE_HOME") .. "/night-notes.txt\n" })
    host.search("night", 400)
    test.wait(function() return host.row("night-notes.txt") end, 2000, "the file never landed")
    test.truthy(host.row("Night light"), "no tile or page")
    local tags = {}
    for _, r in ipairs(test.ipc("rows")) do tags[r.tag or r.kind] = true end
    test.truthy(tags.Setting or tags.Tile, "no setting among the results")
    test.truthy(tags.File, "no file among the results")
    host.search("fixture")
    test.truthy(host.row("Fixture Browser"), "no app")
    host.search("dark")
    test.truthy(host.row("Dark"), "no shell action")
    host.search("lock the")
    test.truthy(host.row("Lock the screen"), "no system action")
    host.search("timer")
    test.truthy(host.row("Timer"), "no mode")
  end)

  test.it("lists a pinned Settings tile's status, and toggles it in place", function()
    host.load()
    host.search("wi-fi")
    local tile
    for _, r in ipairs(test.ipc("rows")) do
      if r.tag == "Tile" then tile = r end
    end
    test.truthy(tile, "no Wi-Fi tile")
    test.ipc("activate")
    test.truthy(test.ipc("state").open, "a tile keeps the launcher up")
  end)

  test.it("gives an app that ties with a page the better place", function()
    host.load()
    host.search("fixture browser")
    test.eq(host.names()[1], "Fixture Browser")
  end)

  test.it("knows every page and tile of the Settings", function()
    host.load()
    local missing = test.ipc("settings_missing")
    test.eq(missing, {}, "pages or tiles the search does not know")
  end)

  test.it("marks the matched letters", function()
    host.load()
    host.search("fixture")
    test.truthy(host.row("Fixture Browser").spans)
  end)

  test.it("searches the id of an app whose name does not match", function()
    host.load()
    host.search("private window")
    test.truthy(host.row("Fixture Browser: New Private Window"), "no desktop action among the results")
  end)
end)

test.describe("the action panel", function()
  test.it("lists a desktop file's actions, and runs one", function()
    host.load()
    host.search("fixture browser")
    local names = test.ipc("act_names")
    test.contains(names, "New Window")
    test.contains(names, "New Private Window")
    test.contains(names, "Pin to favourites")
    test.contains(names, "Run as root")
    test.contains(names, "Open containing folder")
    test.ipc("do_action", "New Private Window")
    test.truthy(host.logged("action private of fixture-browser"))
  end)

  test.it("runs an app as root through polkit", function()
    host.load()
    host.search("fixture browser")
    test.ipc("do_action", "Run as root")
    test.truthy(host.logged("start pkexec env"), "no pkexec")
    test.truthy(host.logged("fixture-browser"))
  end)

  test.it("opens on Ctrl+K and Tab alike, on any row", function()
    host.load()
    host.search("fixture browser")
    test.key("k", "ctrl")
    test.advance(200)
    test.ne(test.ipc("state").acting, "")
    test.truthy(host.row("New Window"))
    test.key("k", "ctrl")
    test.advance(200)
    test.eq(test.ipc("state").acting, "")
  end)

  test.it("pins a result to the favourites, which lead the home page", function()
    host.load()
    host.search("fixture editor")
    test.ipc("do_action", "Pin to favourites")
    host.search("")
    test.eq(test.ipc("rows")[1].name, "Favourites")
    test.eq(test.ipc("rows")[2].name, "Fixture Editor")
    test.eq(test.ipc("setting", "launcher.favourites"), { "app:fixture-editor" })
    host.search("fixture editor")
    test.contains(test.ipc("act_names"), "Unpin from favourites")
  end)

  test.it("hides an app, and brings it back", function()
    host.load()
    host.search("fixture editor")
    test.ipc("do_action", "Hide it")
    test.advance(200)
    host.search("fixture editor")
    test.falsy(host.row("Fixture Editor"))
    host.search("> hidden ")
    test.eq(host.names()[1], "Fixture Editor")
    test.ipc("activate")
    test.advance(200)
    host.search("fixture editor")
    test.truthy(host.row("Fixture Editor"))
  end)

  test.it("runs a terminal application in a terminal", function()
    host.load()
    host.search("fixture top")
    test.ipc("activate")
    test.truthy(host.logged("launch fixture-top"))
  end)

  test.it("shows a row in large type", function()
    host.load()
    host.search("fixture browser")
    test.ipc("do_action", "Show in large type")
    test.advance(200)
    test.eq(test.ipc("state").large, "Fixture Browser")
    test.truthy(test.get("launcher-large").visible)
    test.key("Escape")
    test.advance(200)
    test.eq(test.ipc("state").large, "")
    test.truthy(test.ipc("state").open)
  end)
end)

test.describe("the keyboard", function()
  test.it("picks the nth result with Ctrl or Alt and a number", function()
    host.load()
    host.search("fixture")
    local second = host.names()[2]
    test.key("2", "ctrl")
    test.advance(300)
    test.falsy(test.ipc("state").open, "Ctrl+2 did not pick")
    test.truthy(host.logged("launch"), second)
    host.load()
    host.search("fixture")
    test.key("1", "alt")
    test.advance(300)
    test.falsy(test.ipc("state").open, "Alt+1 did not pick")
  end)

  test.it("completes a mode with Tab", function()
    host.load()
    test.type("tim")
    test.advance(200)
    test.key("Tab")
    test.advance(200)
    test.eq(test.ipc("state").query, "> timer ")
    test.eq(test.get("launcher-search").text, "> timer ")
    test.eq(test.ipc("state").name, "Timer")
  end)

  test.it("completes a mode's name to its prefix", function()
    host.load()
    test.type("clipb")
    test.advance(200)
    test.key("Tab")
    test.advance(200)
    test.eq(test.ipc("state").query, ";")
  end)

  test.it("completes a web bang, and leaves a row's actions to Tab where nothing completes", function()
    host.load()
    host.search("?g")
    test.ipc("q", "?gh")
    test.advance(200)
    test.key("Tab")
    test.advance(200)
    test.eq(test.ipc("state").query, "?gh ")
    host.search("fixture browser")
    test.key("Tab")
    test.advance(200)
    test.ne(test.ipc("state").acting, "")
  end)

  test.it("walks back through past searches with Up in an empty box", function()
    host.load()
    test.type("fixture editor")
    test.advance(200)
    test.key("Return")
    test.settle(600)
    test.ipc("launcher", "open")
    test.settle(600)
    test.type("fixture browser")
    test.advance(200)
    test.key("Return")
    test.settle(600)
    test.ipc("launcher", "open")
    test.settle(600)
    test.eq(test.ipc("state").query, "")
    test.key("Up")
    test.advance(200)
    test.eq(test.ipc("state").query, "fixture browser")
    test.key("Up")
    test.advance(200)
    test.eq(test.ipc("state").query, "fixture editor")
    test.key("Down")
    test.advance(200)
    test.eq(test.ipc("state").query, "fixture browser")
    test.key("Down")
    test.advance(200)
    test.eq(test.ipc("state").query, "")
  end)

  test.it("moves the list, not the history, once there is text", function()
    host.load()
    host.search("fixture")
    test.key("Down")
    test.advance(200)
    test.eq(test.ipc("state").query, "fixture")
    test.eq(test.ipc("state").selected, 2)
    test.key("Up")
    test.advance(200)
    test.eq(test.ipc("state").selected, 1)
  end)

  test.it("types a space in the field until the list has been walked", function()
    host.load()
    test.type("fixture ")
    test.advance(200)
    test.eq(test.get("launcher-search").text, "fixture ")
  end)

  test.it("clears the field with Ctrl+U", function()
    host.load()
    test.type("one two")
    test.advance(100)
    test.key("u", "ctrl")
    test.advance(100)
    test.eq(test.ipc("state").query, "")
  end)

  test.it("leaves Ctrl+W to the shell, which shuts what is open", function()
    host.load()
    test.type("one")
    test.advance(100)
    test.key("w", "ctrl")
    test.settle(600)
    test.falsy(test.ipc("state").open)
  end)

  test.it("walks the list with Ctrl+J and Ctrl+P, and the modes with Ctrl+Tab", function()
    host.load()
    host.search("fixture")
    test.key("j", "ctrl")
    test.advance(100)
    test.eq(test.ipc("state").selected, 2)
    test.key("p", "ctrl")
    test.advance(100)
    test.eq(test.ipc("state").selected, 1)
    host.search("")
    test.key("Tab", "ctrl")
    test.advance(100)
    test.eq(test.ipc("state").query, "/")
    test.key("Tab", "ctrl")
    test.advance(100)
    test.eq(test.ipc("state").query, ";")
  end)

  test.it("remembers what a word led to", function()
    host.load()
    host.search("fix")
    test.key("Down")
    test.advance(100)
    local picked = test.ipc("chosen")
    test.ipc("activate")
    test.settle(600)
    test.ipc("launcher", "open")
    test.settle(600)
    host.search("fix")
    test.eq(host.names()[1], picked, "the word did not find what it found before")
  end)
end)

test.describe("answers that land late", function()
  test.it("asks once for a burst of typing", function()
    host.load { path = { "fd" } }
    test.stub_run("fd", { code = 0, stdout = "" })
    test.key("/")
    for _, letter in ipairs { "n", "o", "t", "e", "s" } do
      test.key(letter)
      test.advance(20)
    end
    test.advance(400)
    local asks = 0
    for _, argv in ipairs(test.runs()) do
      if argv[1] == "fd" then
        asks = asks + 1
        test.contains(argv, "notes")
      end
    end
    test.eq(asks, 1, "every keystroke asked")
  end)

  test.it("keeps the list and the highlight while files land", function()
    local folder = morf.env("XDG_CACHE_HOME")
    host.load { path = { "fd" } }
    test.stub_run("fd", { code = 0, stdout = folder .. "/fixture-a.txt\n" .. folder .. "/fixture-b.txt\n" })
    test.ipc("q", "fixture")
    test.advance(40)
    local before = #test.ipc("rows")
    test.truthy(before > 0, "nothing listed until the files landed")
    test.key("Down")
    local held = test.ipc("chosen")
    test.wait(function()
      test.advance(16)
      return host.row("fixture-a.txt") ~= nil
    end, 3000, "the files never landed")
    test.eq(test.ipc("chosen"), held, "the highlight moved under the person")
  end)

  test.it("shows the last answer until the next one lands", function()
    host.load { path = { "fd" } }
    test.stub_run("fd", { code = 0, stdout = "/tmp/first\n" })
    host.search("/first", 300)
    test.wait(function()
      test.advance(16)
      return host.row("first") ~= nil
    end, 2000)
    test.stub_run("fd", { code = 0, stdout = "/tmp/second\n" })
    test.ipc("q", "/second")
    test.advance(10)
    test.truthy(host.row("first"), "the list flashed empty")
    test.wait(function()
      test.advance(16)
      return host.row("second") ~= nil
    end, 2000)
  end)

  test.it("answers going back over what was typed without asking again", function()
    host.load { path = { "fd" } }
    test.stub_run("fd", { code = 0, stdout = "/tmp/kept\n" })
    host.search("/kept", 300)
    test.wait(function()
      test.advance(16)
      return host.row("kept") ~= nil
    end, 2000)
    host.search("/other", 300)
    local before = #test.runs()
    host.search("/kept", 300)
    test.eq(#test.runs(), before, "the same question was asked twice")
    test.truthy(host.row("kept"))
  end)

  test.it("searches a thousand apps inside a frame's budget", function()
    host.load()
    local ms = test.ipc("timed_search")
    test.note("universal search over 1000 extra rows: " .. tostring(ms) .. " ms")
    test.truthy(ms < 16, "a keystroke took " .. tostring(ms) .. " ms")
    test.eq(#test.logs("warn"), 0)
  end)
end)
